#!/usr/bin/env node
/**
 * Build src/freight/germanStatesData.js: Germany's 16 states from the
 * bundled Natural Earth admin-1 pack (public domain), so a checked route
 * knows which states it crosses (state holidays ban trucks only there)
 * without the browser loading the 3.6 MB world pack.
 *
 * Usage: node scripts/build-german-states.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pack = JSON.parse(
  await readFile(
    path.join(root, 'src/data/local_data/natural_earth/states_provinces.json'),
    'utf8',
  ),
);
const states = pack.features
  .filter((feature) => feature.iso2 === 'DE')
  .map((feature) => ({
    code: feature.iso.replace(/^DE-/, ''),
    decimals: feature.d ?? pack.meta.decimals,
    polygons: feature.polygons,
  }))
  .sort((a, b) => a.code.localeCompare(b.code));
if (states.length !== 16)
  throw new Error(`expected 16 states, got ${states.length}`);

const out = `// Generated by scripts/build-german-states.mjs; do not edit.
// Natural Earth 10m admin-1 (public domain), Germany's 16 states. Rings are
// open, integers in 10^-decimals degrees, first vertex absolute, then
// [dLon, dLat] deltas; the first ring of a polygon is its outline.
export const GERMAN_STATE_SHAPES = ${JSON.stringify(states)};
`;
await writeFile(path.join(root, 'src/freight/germanStatesData.js'), out);
console.log(`wrote ${states.length} states, ${out.length} bytes`);
