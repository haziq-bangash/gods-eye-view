#!/usr/bin/env node
/**
 * Build src/nadeloehr/germanCitiesData.js: the cities in Germany from the
 * bundled Natural Earth populated places (public domain), with their German
 * names, so the search can suggest them the moment a reader types, before
 * the place search answers.
 *
 * Usage: node scripts/build-german-cities.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stateAt } from '../src/freight/germanStates.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pack = JSON.parse(
  await readFile(
    path.join(root, 'src/data/local_data/natural_earth/populated_places.json'),
    'utf8',
  ),
);
// Natural Earth names some German cities in English; the search shows the
// German name and still matches the English one.
const GERMAN = {
  Munich: 'München',
  Cologne: 'Köln',
  Hanover: 'Hannover',
  Frankfurt: 'Frankfurt am Main',
};
const cities = pack.places
  .map(([name, lat, lon, scalerank, rankMax]) => ({
    name: GERMAN[name] || name,
    alt: GERMAN[name] ? [name] : [],
    lat,
    lon,
    state: stateAt([lon, lat]),
    // Bigger first: Natural Earth's population class.
    size: rankMax,
    scalerank,
  }))
  .filter((city) => city.state)
  .sort((a, b) => b.size - a.size || a.scalerank - b.scalerank)
  .map(({ scalerank, ...city }) => city);

const out = `// Generated by scripts/build-german-cities.mjs; do not edit.
// Natural Earth 10m populated places (public domain) inside Germany.
export const GERMAN_CITIES = ${JSON.stringify(cities, null, 2)};
`;
await writeFile(path.join(root, 'src/nadeloehr/germanCitiesData.js'), out);
console.log(`wrote ${cities.length} cities`);
